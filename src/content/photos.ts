export type PhotoKey = keyof typeof photos;

const HOST = "https://images.unsplash.com";

/** Sized and compressed by Unsplash; next/image then serves its own responsive copies. */
export const photoUrl = (key: PhotoKey, width = 1200): string =>
  `${HOST}/${photos[key].id}?auto=format&fit=crop&w=${width}&q=75`;

export const photoImage = (key: PhotoKey, alt?: string, width = 1200) => ({
  src: photoUrl(key, width),
  alt: alt ?? photos[key].alt,
});

